#!/usr/bin/env python3
"""
Refresh repository activity for every entry in data/catalog.yml.

For each repository (the entry's `status_from`, else its `repo`):

1. Find the branch to check (the entry's `branch`, else the default branch)
   with `git ls-remote`, and the date of its latest commit with a shallow,
   tree-less clone. This works for GitHub, GitLab, Bitbucket, and other git
   hosts, and needs no token.
2. For GitHub repositories, read the `archived` flag from the GitHub API when
   GITHUB_TOKEN is set.

Results go to data/repo_status.yml. Values that a run cannot fetch are kept
from the previous file, so a network failure does not erase data.

Usage:
    python scripts/update_repo_status.py
"""

import concurrent.futures
import datetime as dt
import os
import re
import subprocess
import tempfile
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "data" / "catalog.yml"
STATUS = ROOT / "data" / "repo_status.yml"
TIMEOUT_S = 120
GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
GH_RE = re.compile(r"https://github\.com/([^/]+)/([^/#?]+)")


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        timeout=TIMEOUT_S,
        env={**os.environ, "GIT_TERMINAL_PROMPT": "0"},
    )


def default_branch(url: str) -> str | None:
    """Return the default branch of a remote repository, or None."""
    res = _git("ls-remote", "--symref", url, "HEAD")
    match = re.search(r"ref: refs/heads/(\S+)\s+HEAD", res.stdout)
    return match.group(1) if match else None


def last_commit(url: str, branch: str) -> str | None:
    """Return the committer date (YYYY-MM-DD) of the branch tip, or None."""
    with tempfile.TemporaryDirectory() as tmp:
        res = _git("clone", "-q", "--bare", "--depth", "1", "--filter=tree:0",
                   "--single-branch", "--branch", branch, url, tmp)
        if res.returncode != 0:
            return None
        res = _git("-C", tmp, "log", "-1", "--format=%cI")
        return res.stdout.strip()[:10] or None


def github_archived(url: str) -> bool | None:
    """Return the GitHub `archived` flag, or None when unavailable."""
    match = GH_RE.match(url)
    if not match or not GITHUB_TOKEN:
        return None
    owner, repo = match.group(1), match.group(2).removesuffix(".git")
    try:
        resp = requests.get(
            f"https://api.github.com/repos/{owner}/{repo}",
            headers={"Authorization": f"Bearer {GITHUB_TOKEN}"},
            timeout=30,
        )
        resp.raise_for_status()
        return bool(resp.json().get("archived"))
    except requests.RequestException as err:
        print(f"  GitHub API error for {url}: {err}")
        return None


def probe(url: str, branch: str | None) -> dict:
    """Collect the status fields for one repository."""
    result: dict = {}
    branch = branch or default_branch(url)
    if branch:
        result["branch"] = branch
        date = last_commit(url, branch)
        if date:
            result["last_commit"] = date
    archived = github_archived(url)
    if archived is not None:
        result["archived"] = archived
    return result


def main() -> None:
    catalog = yaml.safe_load(CATALOG.read_text())
    old = {}
    if STATUS.exists():
        old = (yaml.safe_load(STATUS.read_text()) or {}).get("repos", {}) or {}

    targets: dict[str, str | None] = {}
    for pkg in catalog["packages"]:
        url = pkg.get("status_from") or pkg.get("repo")
        if url:
            # `branch` applies only to the entry's own repository.
            targets[url] = None if pkg.get("status_from") else pkg.get("branch")

    print(f"Checking {len(targets)} repositories...")
    repos = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        futures = {pool.submit(probe, url, br): url for url, br in targets.items()}
        for future in concurrent.futures.as_completed(futures):
            url = futures[future]
            try:
                fresh = future.result()
            except Exception as err:  # noqa: BLE001 - keep going on any failure
                print(f"  {url}: {err}")
                fresh = {}
            merged = {**old.get(url, {}), **fresh}
            if not fresh.get("last_commit"):
                print(f"  {url}: could not read last commit, kept previous value")
            repos[url] = merged

    header = (
        "# Generated by scripts/update_repo_status.py. Do not edit by hand.\n"
        "# Edit data/catalog.yml instead.\n"
    )
    body = {
        "generated": dt.date.today().isoformat(),
        "repos": dict(sorted(repos.items())),
    }
    STATUS.write_text(header + yaml.safe_dump(body, sort_keys=False, allow_unicode=True))
    print(f"Wrote {STATUS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
