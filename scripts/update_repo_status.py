#!/usr/bin/env python3
"""Refresh last-commit dates and archived flags for every repo in data/catalog.yml.

Replaces update_repo_dates.py, which regex-rewrote the date column of
hand-maintained markdown tables and only understood GitHub. This version
asks git itself, so Bitbucket, GitLab, and git.whoi.edu repositories work
too, and it writes to data/repo_status.yml instead of touching any page.
The GitHub API is only used for the archived flag, which git cannot see.

A repository that cannot be reached keeps its previous values, so a flaky
host or a rate limit never blanks the catalog.

Usage:
    python scripts/update_repo_status.py
    GITHUB_TOKEN=... python scripts/update_repo_status.py -v
"""

from __future__ import annotations

import argparse
import logging
import os
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import requests
import yaml

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[1]
CATALOG_PATH = ROOT / "data" / "catalog.yml"
STATUS_PATH = ROOT / "data" / "repo_status.yml"

GIT_TIMEOUT_S = 120  # generous; a tree-less clone fetches only one commit object
API_TIMEOUT_S = 30
DEFAULT_JOBS = 8     # modest, so we stay polite to the git hosts

# `git ls-remote --symref <url> HEAD` prints the default branch on its own line:
#
#   ref: refs/heads/jazzy	HEAD
#   7609d1bd90ce7edb29d040a082f949e8b089c864	HEAD
#                   ^branch
_SYMREF_RE = re.compile(r"ref: refs/heads/(\S+)\s+HEAD")
_GITHUB_RE = re.compile(r"https://github\.com/([^/]+)/([^/#?]+)")

_STATUS_HEADER = (
    "# Generated by scripts/update_repo_status.py. Do not edit by hand.\n"
    "# Edit data/catalog.yml instead.\n"
)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Refresh repository activity for the site catalog.")
    p.add_argument("-c", "--catalog", type=Path, default=CATALOG_PATH)
    p.add_argument("-o", "--output", type=Path, default=STATUS_PATH)
    p.add_argument("-j", "--jobs", type=int, default=DEFAULT_JOBS)
    p.add_argument("-v", "--verbose", action="store_true")
    args = p.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )

    try:
        refresh_repo_status(args.catalog, args.output, jobs=args.jobs)
    except Exception as e:
        logger.exception("status refresh failed: %s", e)
        return 1
    return 0


def refresh_repo_status(catalog_path: Path, status_path: Path, *, jobs: int = DEFAULT_JOBS) -> None:
    """Probe every catalog repository and rewrite the status file.

    Entries that point their activity at another repository (``status_from``)
    are probed on that repository's default branch; an entry's own
    ``branch`` applies only to its own ``repo``.
    """
    catalog = yaml.safe_load(catalog_path.read_text())
    previous: dict[str, Any] = {}
    if status_path.exists():
        previous = (yaml.safe_load(status_path.read_text()) or {}).get("repos") or {}

    targets = collect_targets(catalog["packages"])
    token = os.environ.get("GITHUB_TOKEN") or None
    if token is None:
        logger.info("GITHUB_TOKEN not set, archived flags kept from %s", status_path.name)
    logger.info("checking %d repositories with %d workers", len(targets), jobs)

    repos: dict[str, Any] = {}
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        futures = {pool.submit(probe_repo, url, branch, token=token): url
                   for url, branch in targets.items()}
        for future in as_completed(futures):
            url = futures[future]
            try:
                fresh = future.result()
            except Exception as e:  # one bad repo must not drop the other hundred
                logger.warning("%s: probe failed, kept previous values: %s", url, e)
                fresh = {}
            if "last_commit" not in fresh:
                logger.warning("%s: no last commit, kept previous value %s",
                               url, previous.get(url, {}).get("last_commit") or "none recorded")
            repos[url] = {**previous.get(url, {}), **fresh}

    body = {
        "generated": datetime.now(timezone.utc).date().isoformat(),
        "repos": dict(sorted(repos.items())),
    }
    status_path.parent.mkdir(parents=True, exist_ok=True)
    status_path.write_text(_STATUS_HEADER + yaml.safe_dump(body, sort_keys=False, allow_unicode=True))
    logger.info("wrote %d repositories → %s", len(repos), status_path)


def collect_targets(packages: list[dict[str, Any]]) -> dict[str, str | None]:
    """Map each repository URL to probe onto the branch to check (None = default)."""
    targets: dict[str, str | None] = {}
    for pkg in packages:
        if pkg.get("status_from"):
            targets.setdefault(pkg["status_from"], None)
        elif pkg.get("repo"):
            targets[pkg["repo"]] = pkg.get("branch")
    return targets


def probe_repo(url: str, branch: str | None, *, token: str | None = None) -> dict[str, Any]:
    """Collect ``branch``, ``last_commit``, and ``archived`` for one repository.

    Missing keys mean "could not tell", never "false"; the caller merges
    over the previous record.
    """
    result: dict[str, Any] = {}
    branch = branch or fetch_default_branch(url)
    if branch:
        result["branch"] = branch
        last = fetch_last_commit_date(url, branch)
        if last:
            result["last_commit"] = last
    archived = fetch_github_archived(url, token) if token else None
    if archived is not None:
        result["archived"] = archived
    return result


def fetch_default_branch(url: str) -> str | None:
    res = _run_git("ls-remote", "--symref", url, "HEAD")
    match = _SYMREF_RE.search(res.stdout) if res else None
    if match is None:
        logger.debug("%s: no default branch from ls-remote", url)
    return match.group(1) if match else None


def fetch_last_commit_date(url: str, branch: str) -> str | None:
    """Committer date (YYYY-MM-DD, UTC) of the branch tip.

    A depth-1, tree-less bare clone downloads one commit object, so this
    costs the same for a three-file driver as for ardupilot.
    """
    with tempfile.TemporaryDirectory() as tmp:
        res = _run_git("clone", "-q", "--bare", "--depth", "1", "--filter=tree:0",
                       "--single-branch", "--branch", branch, url, tmp)
        if res is None or res.returncode != 0:
            logger.debug("%s: clone of %s failed: %s", url, branch, res.stderr.strip() if res else "timeout")
            return None
        res = _run_git("-C", tmp, "log", "-1", "--format=%cI")
    if res is None or not res.stdout.strip():
        return None
    stamp = datetime.fromisoformat(res.stdout.strip())
    return stamp.astimezone(timezone.utc).date().isoformat()


def fetch_github_archived(url: str, token: str) -> bool | None:
    match = _GITHUB_RE.match(url)
    if match is None:
        return None
    owner, repo = match.group(1), match.group(2).removesuffix(".git")
    try:
        resp = requests.get(f"https://api.github.com/repos/{owner}/{repo}",
                            headers={"Authorization": f"Bearer {token}"}, timeout=API_TIMEOUT_S)
        resp.raise_for_status()
    except requests.RequestException as e:
        logger.warning("%s: GitHub API error, archived flag kept: %s", url, e)
        return None
    return bool(resp.json().get("archived"))


def _run_git(*args: str) -> subprocess.CompletedProcess[str] | None:
    # GIT_TERMINAL_PROMPT=0 makes a private or renamed repo fail fast instead
    # of hanging the CI job on a credential prompt.
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True, timeout=GIT_TIMEOUT_S,
                              env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    except subprocess.TimeoutExpired:
        logger.warning("git %s timed out after %d s", args[0], GIT_TIMEOUT_S)
        return None


if __name__ == "__main__":
    sys.exit(main())
